import { createHash } from "node:crypto";
import { NextResponse } from "next/server";
import { backendAuthedFetch } from "@/lib/backend-auth";

const KEYS = ["dryRun", "scope", "version", "pos", "from", "to", "lkcSource"] as const;

function filename(params: URLSearchParams): string {
  const version = (params.get("version") || "1.1").replace(/[^\w.-]/g, "");
  const scope = params.get("scope") || "all";
  const safeDate = (v: string | null) => (v ?? "").replace(/[^\d-]/g, "");
  const suffix =
    scope === "new"
      ? `_new_${new Date().toLocaleDateString("en-CA", { timeZone: "Asia/Dhaka" })}`
      : scope === "xml"
        ? "_original"
        : scope === "range"
          ? `_${safeDate(params.get("from"))}_to_${safeDate(params.get("to"))}`
          : "";
  return `Bangla_Mono_Lingual_Lexicons_v${version}${suffix}.xml`;
}

/**
 * UKC LMF XML export (SRS §10), generated by the backend from the lexicon tables.
 * `scope` = new | all | xml | range; `dryRun=1` returns projected counts only.
 */
export async function GET(req: Request) {
  try {
    const { searchParams } = new URL(req.url);
    const qs = new URLSearchParams();
    for (const key of KEYS) {
      const value = searchParams.get(key);
      if (value) qs.set(key, value);
    }
    const result = await backendAuthedFetch(`/api/export?${qs.toString()}`, { cache: "no-store" });
    if (qs.get("dryRun") === "1" || !result.ok) return result.response;

    // The backend answers with XML; backendFetch keeps non-JSON bodies under `error`.
    const xml = String((result.data as { error?: unknown }).error ?? "");
    const response = new NextResponse(xml, {
      headers: {
        "Content-Type": "application/xml; charset=utf-8",
        "Content-Disposition": `attachment; filename="${filename(qs)}"`,
        "X-Export-SHA256": createHash("sha256").update(xml, "utf8").digest("hex"),
        "Cache-Control": "no-store",
      },
    });
    for (const cookie of result.response.cookies.getAll()) response.cookies.set(cookie);
    return response;
  } catch (err) {
    console.error("[export]", err);
    return NextResponse.json({ error: "Export service unavailable." }, { status: 503 });
  }
}
